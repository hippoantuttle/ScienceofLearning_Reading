import {readFileSync, writeFileSync} from 'node:fs';
import {tokens, aliases} from './tokens.mjs';

// Chrome 116: explicit modes rather than light-dark()/@scope. Astryx validates
// the authoring theme first (`npm run build`). Only this CSS ships in the ZIP.
const values = mode => Object.entries(tokens).map(([name, value]) =>
  `  ${name}: ${Array.isArray(value) ? value[mode] : value};`).join('\n');
const bridges = Object.entries(aliases).map(([name, token]) => `  ${name}: var(${token});`).join('\n');
const css = `/* Generated by design-system/export-css.mjs from the Astryx theme. Do not edit. */
:root {
  color-scheme: light dark;
${values(0)}
${bridges}
}
@media (prefers-color-scheme: dark) {
  :root {
${values(1).split('\n').map(line => '  ' + line).join('\n')}
  }
}
`;
const target = new URL('../ui-theme.css', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== css) throw Error('ui-theme.css is stale; run npm run build in design-system');
  console.log('Static extension theme matches Astryx source.');
} else {
  writeFileSync(target, css);
  console.log('Generated ui-theme.css (Chrome 116 compatible).');
}
